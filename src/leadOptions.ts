// Helper to find a country by exact or partial name
export function findCountry(name?: string | null): Country | undefined {
  if (!name) return undefined;
  const clean = name.trim().toLowerCase();
  return COUNTRIES.find(c => c.name.toLowerCase() === clean || c.code.toLowerCase() === clean);
}

// Helper to extract dial code and local number from an existing phone string
export function parsePhone(phoneStr?: string | null, countryName?: string | null): { dialCode: string; localNumber: string } {
  const p = (phoneStr || '').trim();
  const c = findCountry(countryName);
  const defaultDial = c?.dialCode || '+91';

  if (!p) {
    return { dialCode: defaultDial, localNumber: '' };
  }

  // Check if phone starts with a known dial code
  // Sort countries by dialCode length descending so "+1-242" matches before "+1"
  const sorted = [...COUNTRIES].sort((a, b) => b.dialCode.length - a.dialCode.length);
  for (const item of sorted) {
    const d = item.dialCode;
    // Check e.g. "+91 9876543210" or "+919876543210" or "+91-9876543210"
    if (p.startsWith(d)) {
      const rest = p.slice(d.length).trim().replace(/^[- ]+/, '');
      return { dialCode: d, localNumber: rest };
    }
  }

  // If starts with generic "+<digits>"
  const match = p.match(/^(\+\d{1,4})[\s-]*(.*)$/);
  if (match) {
    return { dialCode: match[1], localNumber: match[2] };
  }

  return { dialCode: defaultDial, localNumber: p };
}
